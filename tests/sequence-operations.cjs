const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const dir=path.join(__dirname,'..');const ctx={};ctx.globalThis=ctx;
for(const file of ['clip-timeline.js','clip-edit-ops.js','clip-graphics.js','sequence-operations.js'])vm.runInNewContext(fs.readFileSync(path.join(dir,file),'utf8'),ctx);
const {MangoSequenceOps:ops,MangoEditOps:ed}=ctx;
const clips=[{start:0,end:30},{start:30,end:60},{start:60,end:90}];
const layers=[{id:'before',start:5,end:10},{id:'crossing',start:25,end:45},{id:'after',start:50,end:80},{id:'inside',start:31,end:41}];
const markers=[{time:5,label:'before'},{time:32,label:'removed'},{time:65,label:'after'}];
const deleted=ops.clip(clips,layers,markers,1);
assert.equal(ed.length(deleted.segments),60);
assert.deepEqual(Array.from(deleted.segments,x=>[x.start,x.end]),[[0,30],[60,90]],'Delete middle clip must keep source boundaries');
assert.deepEqual(Array.from(deleted.markers,x=>[x.time,x.label]),[[5,'before'],[35,'after']],'Markers must ripple and deleted markers must disappear');
assert.deepEqual(Array.from(deleted.layers,x=>[x.id,x.start,x.end]),[['before',5,10],['crossing',25,30],['after',30,50]],'Graphics must ripple, overlap shorten, and fully deleted graphics disappear');
assert.equal(deleted.playhead,30);
const sub=ops.range(clips,layers,markers,20,40);
assert.equal(ed.length(sub.segments),70);assert.equal(sub.removed,20);
assert.deepEqual(Array.from(sub.segments,x=>[x.start,x.end]),[[0,20],[40,60],[60,90]]);
const trimmed=ops.trim(clips,layers,markers,10,40);
assert.equal(ed.length(trimmed.segments),30);
assert.deepEqual(Array.from(trimmed.markers,x=>x.time),[22]);
assert.deepEqual(Array.from(trimmed.layers,x=>[x.id,x.start,x.end]),[['crossing',15,30],['inside',21,30]],'Trim graphics are rebased to new sequence zero');
const edge=ops.edge(clips,layers,markers,1,'start',35,90);
assert.equal(ed.length(edge.segments),85);assert.equal(edge.removed,5);
assert.deepEqual(Array.from(edge.markers,x=>x.time),[5,60]);
assert.deepEqual(Array.from(edge.layers,x=>[x.id,x.start,x.end]),[['before',5,10],['crossing',25,40],['after',45,75],['inside',30,36]]);
assert.throws(()=>ops.range(clips,layers,markers,0,90),/entire sequence/);
assert.throws(()=>ops.clip([{start:0,end:90}],layers,markers,0),/entire sequence/);
assert.throws(()=>ops.clip(clips,layers,markers,-1),/Select a V1 video clip/);
assert.throws(()=>ops.range(clips,layers,markers,NaN,10),/Select a valid range/);
assert.deepEqual(Array.from(clips,x=>[x.start,x.end]),[[0,30],[30,60],[60,90]],'Input source must not mutate');
console.log('PASS: ripple V1 clip, range, trim, edge, marker and graphic transactions; original untouched');
