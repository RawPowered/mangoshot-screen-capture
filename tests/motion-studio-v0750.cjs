const assert=require('node:assert/strict'),fs=require('node:fs');
const C=require('../compositor-core-v0714.js'),M=require('../motion-core-v0750.js');
const layer={start:2,end:6,keyframes:[]};
assert.equal(M.at(layer,4),.5);assert.equal(M.at(layer,1),null);assert.equal(M.at(layer,6),1);
let keys=M.upsert([],0,{x:0,y:0,scale:1,rotation:0,opacity:1,ease:'linear'});
keys=M.upsert(keys,1,{x:.6,y:.4,scale:2,rotation:60,opacity:.5});
const midpoint=C.pose(keys,.5);
assert.equal(midpoint.x,.3);assert.equal(midpoint.rotation,30);
const old=JSON.stringify(keys),insert=M.upsert(keys,.5,{rotation:45});
assert.equal(JSON.stringify(keys),old);assert.equal(insert.length,3);assert.equal(insert[1].x,.3);assert.equal(insert[1].rotation,45);
const moved=M.move(insert,.5,.2,-.1);assert.ok(Math.abs(moved[1].x-.5)<1e-9);assert.ok(Math.abs(moved[1].y-.1)<1e-9);assert.equal(moved[1].rotation,45);
assert.equal(M.snap({...layer,keyframes:moved},4.003),.5);
assert.equal(M.adjacent(moved,.5,-1).t,0);assert.equal(M.adjacent(moved,.5,1).t,1);
assert.deepEqual(M.remove(moved,.5),keys);
assert.throws(()=>M.upsert(keys,.5,{rotation:Infinity}));assert.throws(()=>M.upsert(keys,.5,{foo:1}));assert.throws(()=>M.upsert(keys,1.1));assert.throws(()=>M.remove(keys,.5));assert.equal(M.move(keys,.5,9,-9)[1].x,1);
let full=[];for(let i=0;i<C.MAX_KEYS;i++)full=M.upsert(full,i/(C.MAX_KEYS-1));assert.throws(()=>M.upsert(full,.01));assert.equal(M.upsert(full,0,{scale:2}).length,C.MAX_KEYS);
const html=fs.readFileSync('clip-studio.html','utf8'),host=fs.readFileSync('clip-studio.js','utf8'),graphics=fs.readFileSync('clip-graphics-ui.js','utf8');
assert.ok(html.indexOf('motion-core-v0750.js')<html.indexOf('clip-studio.js'));assert.ok(html.includes('ms50-panel')&&html.includes('motion-studio-v0750.js'));
assert.ok(host.includes('commitGraphicMotion(')&&host.includes('previewGraphicMotion('));assert.ok(graphics.includes('commitGraphicMotion(')&&graphics.includes('cancelGraphicMotion('));
console.log('PASS: shared motion pose edits, interpolation, snapping, bounds, limits, and integration anchors');
