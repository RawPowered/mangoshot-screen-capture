const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=fs.realpathSync(__dirname+'/..');const context=vm.createContext({});
for(const name of ['clip-timeline.js','camera.js'])vm.runInContext(fs.readFileSync(root+'/'+name,'utf8'),context);
const m=context.MangoTimeline;
let clips=m.normalize([{start:0,end:30}],30);
clips=m.remove(clips,{start:5,end:12},30);
assert.equal(JSON.stringify(clips),'[{"start":0,"end":5},{"start":12,"end":30}]');
assert.equal(m.outputDuration(clips),23);
assert.equal(m.sourceAt(clips,5.1),12.1);
clips=m.trim(clips,{start:3,end:20},30);
assert.equal(JSON.stringify(clips),'[{"start":3,"end":5},{"start":12,"end":20}]');
assert.throws(()=>m.range(8,2,30));
const c=context.MangoCamera;const initial=c.camera();
assert.deepEqual(JSON.parse(JSON.stringify(initial)),{zoom:1,cx:.5,cy:.5});
const next=c.anchor(initial,2,{x:.75,y:.25});const origin={x:initial.cx+(.75-.5)/initial.zoom,y:initial.cy+(.25-.5)/initial.zoom};
assert.ok(Math.abs(next.cx+(.75-.5)/next.zoom-origin.x)<1e-10);
assert.ok(Math.abs(next.cy+(.25-.5)/next.zoom-origin.y)<1e-10);
const selected=c.box(initial,{x:.2,y:.2},{x:.6,y:.6});assert.ok(Math.abs(selected.zoom-2.5)<1e-10);
const crop=c.crop(selected,1280,720);assert.ok(crop.sw>0&&crop.sx>=0&&crop.sw+crop.sx<=1280);
console.log('PASS: timeline trim, cut, invalid ranges, camera zoom/box/focal anchor');
