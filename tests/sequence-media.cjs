const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const ctx={Float32Array,Math,Number,Array,Error};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','sequence-media.js'),'utf8'),ctx);
const m=ctx.MangoSequenceMedia,clips=[{start:0,end:2},{start:6,end:10}];
assert.equal(m.duration(clips),6);
assert.equal(m.atOutput(clips,1.5).source,1.5);
assert.equal(m.atOutput(clips,2).source,6,'Exact cut jumps directly to next retained source frame');
assert.equal(m.atOutput(clips,5).source,9);
assert.equal(m.atSource(clips,4),null,'Deleted source footage has no retained sequence coordinate');
assert.equal(m.atSource(clips,7).output,3);
const thumbs=m.thumbnailPlan(clips,6);
assert.equal(thumbs.length,6);
assert.equal(thumbs[0].source,.5);
assert.equal(thumbs[2].source,6.5,'Thumbnail after cut must come from the second source interval');
assert.equal(thumbs[5].source,9.5);
const peaks=Float32Array.from([.1,.1,.1,.1,1,1,.1,.6,.2,.2]);
const visual=m.peakSeries(clips,peaks,10,60);
assert.equal(visual.length,60);
assert.ok([...visual].every(p=>p<.8),'Deleted high-amplitude source audio must not appear on A1');
assert.ok([...visual].some(p=>p>.5),'Retained audio must remain visible');
const raw=Float32Array.from([0,.2,-1,.1,0,.4,-.2,.1]);
assert.equal(m.audioPeaks(raw,2).length,2);
console.log('PASS: sequence thumbnails, cut-boundary source mapping and gapless waveform projection');
