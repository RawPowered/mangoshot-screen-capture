const vm=require('node:vm'),fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const local={};local.globalThis=local;let n=0;const revoked=[];
local.URL={createObjectURL:()=> 'blob:local-'+(++n),revokeObjectURL:u=>revoked.push(u)};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','media-assets.js'),'utf8'),local);
const M=local.MangoMediaAssets,registry=M.create({URLApi:local.URL,id:()=> 'asset-'+(n+1)});
const file=(name,type,size=1000,lastModified=123)=>({name,type,size,lastModified});
assert.equal(M.typeOf('photo.PNG','image/png'),'image');
assert.equal(M.typeOf('test.svg','image/svg+xml'),null,'SVG with script must not be accepted');
assert.equal(M.typeOf('video.mp4','text/html'),null,'Extension does not override unrelated MIME type');
let a=registry.register(file('product.webp','image/webp')).asset;
assert.equal(a.kind,'image');assert.equal(registry.count(),1);
assert.equal(registry.register(file('product.webp','image/webp')).duplicate,true,'Exact duplicate reuses same asset');
registry.updateMeta(a.id,{width:2048,height:1080});
assert.equal(registry.get(a.id).width,2048);
assert.throws(()=>registry.updateMeta(a.id,{url:'https://remote.test/asset'}),/read-only/);
assert.throws(()=>registry.register(file('payload.svg','image/svg+xml')),/Unsupported/);
assert.throws(()=>registry.register(file('bad.png','image/png',0)),/nonempty/);
assert.throws(()=>registry.register(file('oversized.mov','video/quicktime',9*1024**3)),/8 GiB/);
assert.equal(registry.snapshot()[0].url,undefined,'Projects never serialize local blob URLs');
assert.equal(registry.snapshot()[0].blob,undefined,'Projects never serialize raw files');
assert.equal(registry.remove(a.id),true);assert.equal(registry.count(),0);assert.equal(revoked.length,1);
const b={id:'missing-1',kind:'audio',name:'music.mp3',mime:'audio/mpeg',size:300,lastModified:9,duration:10,width:null,height:null};
registry.addPlaceholder(b);
assert.equal(registry.get('missing-1').missing,true);
assert.throws(()=>registry.relink('missing-1',file('other.mp3','audio/mpeg',300,9)),/same filename/);
assert.equal(registry.register(file('music.mp3','audio/mpeg',300,9)).duplicate,true,'Importing missing file relinks existing placeholder');
assert.equal(registry.get('missing-1').missing,false);
registry.clear();assert.equal(registry.count(),0);assert.equal(revoked.length,2);
console.log('PASS: media registry import, metadata, dedupe, relink, local cleanup and security limits');
